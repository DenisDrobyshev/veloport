from decimal import Decimal

import pytest
from django.urls import reverse

from apps.catalog.models import Bike, Product
from apps.core.utils import ru_slugify

pytestmark = pytest.mark.django_db


def test_ru_slugify_transliteration():
    assert ru_slugify("Горный велосипед") == "gornyy-velosiped"
    assert ru_slugify("Trek Marlin 7") == "trek-marlin-7"
    assert ru_slugify("Шоссе") == "shosse"


def test_product_slug_autogenerated(product):
    assert product.slug == "trek-marlin-7"


def test_product_price_properties(product):
    assert product.has_discount is True
    assert product.discount_percent == 10
    assert product.savings == Decimal("10000")
    assert product.in_stock is True


def test_product_no_discount(category, brand):
    p = Product.objects.create(category=category, brand=brand, title="X", sku="S1", price=1000)
    assert p.has_discount is False
    assert p.discount_percent == 0


def test_list_view_ok(client, product):
    r = client.get(reverse("catalog:list"))
    assert r.status_code == 200
    assert product.title in r.content.decode()


def test_category_and_brand_views(client, product):
    assert client.get(reverse("catalog:category", args=[product.category.slug])).status_code == 200
    assert client.get(reverse("catalog:brand", args=[product.brand.slug])).status_code == 200


def test_product_detail_increments_views(client, product):
    assert product.views == 0
    r = client.get(product.get_absolute_url())
    assert r.status_code == 200
    product.refresh_from_db()
    assert product.views == 1


def test_facet_filter_by_wheel(client, category, brand):
    p29 = Product.objects.create(category=category, brand=brand, title="Bike29", sku="A", price=50000, stock_qty=1)
    Bike.objects.create(product=p29, wheel_size="29")
    p26 = Product.objects.create(category=category, brand=brand, title="Bike26", sku="B", price=40000, stock_qty=1)
    Bike.objects.create(product=p26, wheel_size="26")
    r = client.get(reverse("catalog:list"), {"wheel": "29"})
    body = r.content.decode()
    assert "Bike29" in body and "Bike26" not in body


def test_price_sort(client, category, brand):
    Product.objects.create(category=category, brand=brand, title="Cheap", sku="C", price=1000, stock_qty=1)
    Product.objects.create(category=category, brand=brand, title="Pricey", sku="P", price=9000, stock_qty=1)
    r = client.get(reverse("catalog:list"), {"sort": "cheap"})
    body = r.content.decode()
    assert body.index("Cheap") < body.index("Pricey")


def test_api_products(client, product):
    r = client.get("/api/products/")
    assert r.status_code == 200
    assert r.json()["count"] >= 1
